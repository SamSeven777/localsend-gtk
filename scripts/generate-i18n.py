for lang, catalog in CATALOGS.items():
    missing = set(gtk_en.keys()) - set(catalog.keys())
    if missing:
        raise ValueError(f"Lang {lang} missing {len(missing)} keys: {missing}")
    extra = set(catalog.keys()) - set(gtk_en.keys())
    if extra:
        raise ValueError(f"Lang {lang} has {len(extra)} extra keys: {extra}")
    for k, v in catalog.items():
        expected_p = extract_placeholders(k)
        if isinstance(v, dict):
            if "other" not in v or set(v) - {"one", "few", "many", "other"}:
                raise ValueError(f"Lang {lang} invalid plural forms for '{k}'")
            if lang == "ru" and not {"one", "few", "many"}.issubset(v):
                raise ValueError(f"Lang {lang} missing cardinal forms for '{k}'")
            forms = v.values()
        else:
            forms = [v]
        for form in forms:
            actual_p = extract_placeholders(form)
            if expected_p != actual_p:
                raise ValueError(f"Lang {lang} placeholder mismatch for '{k}': expected {expected_p}, got {actual_p}")
            if not form.strip():
                raise ValueError(f"Lang {lang} empty translation for '{k}'")
    out_file = I18N_DIR / f"gtk-{lang}.json"
    with open(out_file, "w", encoding="utf-8") as f:
        json.dump(catalog, f, ensure_ascii=False, indent=2)
        f.write("\n")
    print(f"Wrote {out_file.name} with {len(catalog)} verified translations.")
